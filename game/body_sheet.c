static const int sheet_frames[BODY_CLIP_COUNT] = {
    1, 8, 8, 8, 4, 5, 2, 2, 1,
};

/* [body_sheet_frames] Devolve quantos quadros o clip tem. Fora da faixa, devolve 0. */
int body_sheet_frames(int clip)
{
    if (clip < 0 || clip >= BODY_CLIP_COUNT) {
        return 0;
    }
    return sheet_frames[clip];
}

/* [body_sheet_frame] Devolve os 256 índices do quadro. Fora da faixa, devolve 0. */
const uint8_t *body_sheet_frame(int clip, int frame)
{
    int base;
    int i;

    if (clip < 0 || clip >= BODY_CLIP_COUNT) {
        return 0;
    }
    if (frame < 0 || frame >= sheet_frames[clip]) {
        return 0;
    }
    base = 0;
    for (i = 0; i < clip; i++) {
        base += sheet_frames[i];
    }
    base += frame;
    return sheet_px + base * BODY_SHEET_W * BODY_SHEET_H;
}
